import React from 'react';
import { render, screen } from '@testing-library/react';
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { ScheduleView } from '../schedule/ScheduleView';
import { ProgressView } from '../progress/ProgressView';
import { StudyProvider } from '@/context/StudyContext';
import { saveToStorage, clearStorage } from '@/lib/storage';
import { StudyPlan } from '@/types';

const mockAiPlan: StudyPlan = {
  id: 'plan-ai-1',
  planTitle: 'Calculus Mastery AI Plan',
  summary: 'AI-tailored study plan with spaced repetition.',
  generatedAt: new Date().toISOString(),
  planningPeriodDays: 7,
  startDate: '2026-11-09',
  dailyHoursLimit: 3,
  preferredSessionMinutes: 45,
  isAiGenerated: true,
  modelUsed: 'gemini-3.8-flash',
  days: [
    {
      date: '2026-11-09',
      tasks: [
        {
          id: 'task-1',
          subjectId: 'sub-calc',
          subjectName: 'Calculus',
          topic: 'Taylor Series',
          durationMinutes: 45,
          priority: 'high',
          reason: 'Exam in 4 days',
          completed: false,
          completedAt: null,
        },
      ],
    },
  ],
  warnings: [],
};

const mockBasicPlan: StudyPlan = {
  ...mockAiPlan,
  id: 'plan-basic-1',
  planTitle: 'Calculus Structured Plan (Basic Plan)',
  isAiGenerated: false,
  modelUsed: 'Deterministic Fallback Planner (No External AI)',
};

describe('ScheduleView Component', () => {
  beforeEach(() => {
    clearStorage();
  });

  it('renders empty schedule prompt when no plan is active', () => {
    render(
      <StudyProvider>
        <ScheduleView
          onNavigateToPlanner={vi.fn()}
          onNavigateToSubjects={vi.fn()}
        />
      </StudyProvider>
    );

    expect(screen.getByText('No Study Schedule Active')).toBeInTheDocument();
  });

  it('renders "AI Plan" badge when active plan was generated by AI', () => {
    saveToStorage({ activePlan: mockAiPlan });

    render(
      <StudyProvider>
        <ScheduleView
          onNavigateToPlanner={vi.fn()}
          onNavigateToSubjects={vi.fn()}
        />
      </StudyProvider>
    );

    const badge = screen.getByTestId('schedule-plan-badge');
    expect(badge).toHaveTextContent('AI Plan');
    expect(screen.getByText('Calculus Mastery AI Plan')).toBeInTheDocument();
  });

  it('renders "Basic Plan" badge when active plan is from deterministic fallback', () => {
    saveToStorage({ activePlan: mockBasicPlan });

    render(
      <StudyProvider>
        <ScheduleView
          onNavigateToPlanner={vi.fn()}
          onNavigateToSubjects={vi.fn()}
        />
      </StudyProvider>
    );

    const badge = screen.getByTestId('schedule-plan-badge');
    expect(badge).toHaveTextContent('Basic Plan');
    expect(screen.getByText('Calculus Structured Plan (Basic Plan)')).toBeInTheDocument();
  });
});

describe('ProgressView Component', () => {
  beforeEach(() => {
    clearStorage();
  });

  it('renders empty progress state when no tasks exist', () => {
    render(
      <StudyProvider>
        <ProgressView
          onNavigateToSchedule={vi.fn()}
          onNavigateToPlanner={vi.fn()}
        />
      </StudyProvider>
    );

    expect(screen.getByText('No Study Progress Data Available')).toBeInTheDocument();
  });
});
